# CRM Customer Analytics & Sales Pipeline Dashboard

## 📌 Project Overview
This comprehensive data analytics project was completed during my formal training coursework. The purpose of this analysis was to process raw Customer Relationship Management (CRM) dataset parameters to understand how active business leads travel through a commercial sales pipeline and convert into closed accounts. By evaluating key performance indicators, this project uncovers client engagement trends to optimize conversion funnels.

