## 🛠️ Technical Stack & Skills Developed
* **Data Visualization (Power BI & Tableau):** Formatted clean, accessible business report layouts. Applied advanced filtering, dimensional slicers, and dynamic KPI cards to enable corporate stakeholder navigation.
* **Data Transformation (Excel):** Utilized Excel Power Query to scan messy customer tables, drop null parameters, standardize structural formatting variations, and organize dataset rows. Built specialized Pivot Tables for quick metrics calculations.
* **Database Querying (SQL):** Wrote backend relational database commands, structured schema scripts, and grouped aggregated queries to clean, check, and count total customer accounts.

## 💡 Core Metrics & Data Insights
* **Lead Conversion Funnel:** Monitored a baseline database of 10,000 potential customer leads, calculating a final monitored Lead Conversion Rate of 10.33% with 1,016 total converted accounts.
* **Pipeline Capacity:** Analyzed dynamic values inside active negotiation stages, isolating a major 42.77% overall opportunity deal Win Rate alongside an estimated 31.06% financial opportunity conversion margin.
* **Traffic Allocation Trends:** Tracked customer acquisition pathways to verify performance volume, finding that "Inside Sales" (2.78K records) and "Websites" (2.19K records) drove the highest volume of consumer engagement.
